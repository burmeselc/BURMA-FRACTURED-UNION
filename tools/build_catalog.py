#!/usr/bin/env python3
"""Validate the editable JSON and generate GitHub Pages / offline assets."""
import json
from pathlib import Path
base=Path(__file__).resolve().parents[1]
data=json.loads((base/"data/1948/catalog.json").read_text(encoding="utf8"))
assert data["schema"]=="burma-fu-catalog/1" and data["version"]=="1.6"
ids=[e["id"] for e in data["entities"]]
assert len(ids)==len(set(ids)), "Duplicate actor ID"
ids=set(ids)
assert all(e["from"] in ids and e["to"] in ids for e in data["relations"])
assert all(e["a"] in ids and e["b"] in ids for e in data["initial_simulation_edges"])
reg={r[0] for r in data["geographies"]["nationalRegions"]}
assert all(not e.get("region") or e["region"] in reg for e in data["entities"])
assert all("local:"+x[0] in ids for x in data["geographies"]["politicalActors"])
assert all("area:shan:"+x["id"] in ids for x in data["geographies"]["shanTerritories"])
js="/* Generated by tools/build_catalog.py from data/1948/catalog.json. DO NOT EDIT. */\nwindow.BURMA_CATALOG="+json.dumps(data,ensure_ascii=False,separators=(",",":"))+";\n"
(base/"data/1948/catalog.generated.js").write_text(js,encoding="utf8")
html=(base/"index.html").read_text(encoding="utf8")
tag='<script src="./data/1948/catalog.generated.js"></script>'
assert html.count(tag)==1
dist=base/"dist/burma_1948_standalone_v16.html"
dist.parent.mkdir(parents=True,exist_ok=True)
dist.write_text(html.replace(tag,"<script>\n"+js+"</script>",1),encoding="utf8")
print("Valid:",len(ids),"actors /",len(data["relations"]),"links")
